#!/bin/bash
# 执行每日数据同步
# 可以被crontab调用，也可以手动执行

# 获取脚本所在目录
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"

# 切换到项目根目录
cd "$SCRIPT_DIR"

# 创建日志目录
mkdir -p logs

echo "========================================================================"
echo "Excel数据同步 - $(date '+%Y-%m-%d %H:%M:%S')"
echo "========================================================================"

# 执行同步
python3 src/alert/daily_sync.py 2>&1 | tee -a logs/sync.log

echo "========================================================================"
echo "同步完成"
echo "========================================================================"

